#!/usr/bin/env python3
"""7.5: write src/AncientRelicValues.Generated.cs from tools/measure_ancient_relics.py output.

    python3 tools/gen_ancient_table.py ancient-relics.json src/AncientRelicValues.Generated.cs --builds "v0.111.x"
"""
import argparse
import json


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('model')
    parser.add_argument('out')
    parser.add_argument('--builds', default='mixed builds', help='text for the header: which game versions the runs came from')
    args = parser.parse_args()
    values = json.load(open(args.model, encoding='utf-8'))['values']
    rows = []
    for character in sorted(values, key=lambda c: (c != 'all', c)):
        for act in sorted(values[character]):
            for relic in sorted(values[character][act]):
                cell = values[character][act][relic]
                rows.append(f'        ["{character}:{act}:{relic}"] = ({cell["pp"]}m, {cell["n"]}),')
    header = f'''// <auto-generated> by tools/measure_ancient_relics.py + tools/gen_ancient_table.py (train split of the run corpus,
// {args.builds}); do not edit by hand.
// Key "character:act:RELICID" (relic id without underscores, character "all" = every character).
// Value: win-rate difference in percentage points between runs that took the relic at that act's
// Ancient and all Ancient picks of that character at that act, shrunk by n / (n + 150); n = runs.
namespace BuildAdvisor.Integration;

internal static partial class AncientRelicValues
{{
    private static readonly Dictionary<string, (decimal Pp, int Runs)> Table = new(StringComparer.Ordinal)
    {{
'''
    open(args.out, 'w', encoding='utf-8', newline='\n').write(header + '\n'.join(rows) + '\n    };\n}\n')
    print(f'{len(rows)} entries -> {args.out}')


if __name__ == '__main__':
    main()
